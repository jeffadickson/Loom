using System.Text;
using System.Text.Json;

namespace Loom.Core;

public static class TypeGenerator
{
    public static void Generate(Catalog catalog, string directory)
    {
        Directory.CreateDirectory(directory);
        foreach (var schema in catalog.Types.Values.OrderBy(t=>t.Name,StringComparer.Ordinal))
        {
            var b = new StringBuilder("// <auto-generated /> DO NOT EDIT. Source: Metadata/" + schema.Name + ".json\n#nullable enable\nnamespace Loom.Generated;\n\n");
            string Q(string value) => JsonSerializer.Serialize(value);
            b.AppendLine($"[Loom.Core.Document({Q(schema.Id!)}, {Q(schema.TitleField)}, Name = {Q(schema.Name)}, Label = {Q(schema.Label)}, Version = {schema.Version}, Immutable = {schema.Immutable.ToString().ToLowerInvariant()}, Submittable = {schema.Submittable.ToString().ToLowerInvariant()})]");
            foreach (var grant in schema.Permissions.OrderBy(p=>p.Key,StringComparer.Ordinal))
                b.AppendLine("[Loom.Core.Grant(" + string.Join(", ", new[] { grant.Key }.Concat(grant.Value).Select(Q)) + ")]");
            b.AppendLine("public sealed partial record @" + schema.Name + "\n{");
            foreach (var f in schema.Fields)
            {
                var type = f.Type switch { "Measurement" => "Loom.Core.Science.Measurement", "Integer" => "long", "Decimal" or "Money" => "decimal", "Binary"=>"byte[]", "Boolean" => "bool", "Date" => "System.DateOnly", _ => "string" };
                var options = f.Options == null ? "" : ", Options = new[] { " + string.Join(", ", f.Options.Select(Q)) + " }";
                var target = f.Target == null ? "" : ", Target = " + Q(f.Target);
                var settings=(f.Currency==null?"":", Currency="+Q(f.Currency))+(f.Precision==null?"":", Precision="+f.Precision+", Scale="+f.Scale)+", Rounding="+Q(f.Rounding)+", DateFormat="+Q(f.DateFormat)+", Compression="+Q(f.Compression)+", MaxBytes="+f.MaxBytes+", MediaType="+Q(f.MediaType)+(f.Type=="Uri"?", Kind=\"Uri\"":"");
                settings += (f.Description==null?"":", Description="+Q(f.Description))+(f.MaxLength==null?"":", MaxLength="+f.MaxLength)+(f.Minimum==null?"":", Minimum="+Q(f.Minimum.Value.ToString(System.Globalization.CultureInfo.InvariantCulture)))+(f.Maximum==null?"":", Maximum="+Q(f.Maximum.Value.ToString(System.Globalization.CultureInfo.InvariantCulture)))+(f.Default==null?"":", Default="+Q(f.Default));
                settings += (f.QuantityKind==null?"":", QuantityKind="+Q(f.QuantityKind))+(f.AllowedUnits==null?"":", AllowedUnits=new[] {"+string.Join(",",f.AllowedUnits.Select(Q))+"}");
                b.AppendLine($"    [Loom.Core.Field({Q(f.Id!)}, Name = {Q(f.Name)}, Label = {Q(f.Label)}, Required = {f.Required.ToString().ToLowerInvariant()}, Unique = {f.Unique.ToString().ToLowerInvariant()}, ReadOnly = {f.ReadOnly.ToString().ToLowerInvariant()}{target}{options}{settings})]");
                b.AppendLine("    [System.Text.Json.Serialization.JsonPropertyName(" + JsonSerializer.Serialize(f.Name) + ")]");
                // @ permits C# keywords; schema field names remain stable, without casing collisions.
                b.AppendLine("    public " + type + "? @" + f.Name + " { get; init; }");
            }
            b.AppendLine("}");
            var path=Path.Combine(directory,schema.Name+".g.cs");var source=b.ToString();
            if(File.Exists(path) && !File.ReadAllText(path).StartsWith("// <auto-generated /> DO NOT EDIT. Source: Metadata/",StringComparison.Ordinal))
                throw new InvalidOperationException("Refusing to overwrite handwritten file: "+path);
            if(!File.Exists(path) || File.ReadAllText(path)!=source)File.WriteAllText(path,source);
        }
    }
}
