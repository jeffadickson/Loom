const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE||undefined,args:['--no-sandbox']});
 const page=await browser.newPage({bypassCSP:true,viewport:{width:1280,height:900}});
 await page.goto('http://127.0.0.1:5080');
 await page.waitForFunction(()=>document.querySelector('#count').textContent!=='—');
 const downloadPromise=page.waitForEvent('download');
 await page.locator('#printReport').click();
 const download=await downloadPromise;assert.equal(download.suggestedFilename(),'Asset_Report.html');
 await download.saveAs('/tmp/loom-equipment-report.html');
 await page.goto('file:///tmp/loom-equipment-report.html');
 assert.match(await page.locator('body').innerText(),/LAB-001/);
 assert.match(await page.locator('body').innerText(),/Category: Electronics/);
 assert.match(await page.locator('body').innerText(),/Grand total/);
 console.log('PASS writer UI: download opens as a standalone grouped report');
 await page.screenshot({path:'/tmp/loom-report-screen.png',fullPage:true});
 await page.emulateMedia({media:'print'});
 assert.equal(await page.locator('.screen').isVisible(),false);
 assert.equal(await page.locator('thead').first().evaluate(el=>getComputedStyle(el).display),'table-header-group');
 await page.screenshot({path:'/tmp/loom-report-print.png',fullPage:true});
 console.log('PASS writer UI: print styling hides instructions and repeats table headings');
 const response=await page.request.get('http://127.0.0.1:5080/api/reports/WorkOrder/print',{headers:{'X-Loom-Demo':'local','X-Demo-Role':'Viewer'}});
 assert.equal(response.status(),200);assert.match(await response.text(),/Estimate/);
 const denied=await page.request.get('http://127.0.0.1:5080/api/reports/Asset/print',{headers:{'X-Loom-Demo':'local','X-Demo-Role':'Unknown'}});
 assert.equal(denied.status(),403);
 console.log('PASS writer API: authorized download and denied role');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
