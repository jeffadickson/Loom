const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_EXECUTABLE,headless:true,args:['--no-sandbox']});
 const page=await browser.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:5080');
 await page.getByRole('button',{name:'Test results',exact:true}).click();
 await page.getByRole('button',{name:'Thermal cycle • channel 1',exact:true}).click();
 await page.locator('#editor').waitFor({state:'visible'});
 if(await page.locator('[name="SampleCount"]').inputValue()!=='9007199254740993')throw Error('Integer rounded in browser');
 if(await page.locator('[name="Temperature"]').inputValue()!=='25')throw Error('Seed measurement missing');
 await page.locator('[name="Temperature"]').fill('298.15');
 await page.locator('[name="Temperature__unit"]').selectOption('K');
 await page.locator('[name="Temperature__uncertainty"]').fill('0.2');
 await page.locator('[name="Cost"]').fill('12345678901234567.89');
 await page.locator('[name="Waveform"]').setInputFiles({name:'waveform.bin',mimeType:'application/octet-stream',buffer:Buffer.from([0,255,1,128,2])});
 await page.locator('#save').click();await page.locator('#editor').waitFor({state:'hidden'});
 await page.getByRole('button',{name:'Thermal cycle • channel 1',exact:true}).click();await page.locator('#editor').waitFor({state:'visible'});
 if(await page.locator('[name="Cost"]').inputValue()!=='12345678901234567.89')throw Error('Money rounded');
 if(await page.locator('[name="Temperature"]').inputValue()!=='298.15'||await page.locator('[name="Temperature__unit"]').inputValue()!=='K'||await page.locator('[name="Temperature__uncertainty"]').inputValue()!=='0.2')throw Error('Measurement roundtrip failed');
 const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Download 5 bytes',exact:true}).click()]);
 const stream=await download.createReadStream();let chunks=[];for await(const chunk of stream)chunks.push(chunk);
 if(!Buffer.concat(chunks).equals(Buffer.from([0,255,1,128,2])))throw Error('Download byte mismatch');
 await page.locator('[name="Cost"]').fill('1.005');await page.locator('#save').click();await page.locator('#formError').waitFor({state:'visible'});
 if(!(await page.locator('#formError').innerText()).includes('scale'))throw Error('Rounding refusal missing');
 await page.locator('#close').click();
 if(errors.length)throw Error(errors.join('\n'));
 console.log('PASS memory browser: exact integer and money edit, file upload/download, scale rejection, measurement/unit/uncertainty editing');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
